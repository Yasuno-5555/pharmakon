#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_score_plan_perfect() {
        let s = score_plan(true, true, 1000);
        assert!(s > 0.8, "perfect plan should score > 0.8, got {}", s);
    }

    #[test]
    fn test_score_plan_failed() {
        let s = score_plan(false, false, 10000);
        assert!(s < 0.3, "failed plan should score < 0.3, got {}", s);
    }

    #[test]
    fn test_score_plan_cheaper_wins() {
        let cheap = score_plan(true, true, 500);
        let expensive = score_plan(true, true, 5000);
        assert!(cheap > expensive, "cheaper plan should score higher");
    }

    #[test]
    fn test_plan_serialization() {
        let plan = CandidatePlan {
            id: "test-1".into(),
            description: "Test plan".into(),
            estimated_tokens: 500,
            steps: vec![PlanStep {
                tool: "codeact".into(),
                args: serde_json::json!({"script": "print('hello')"}),
                depends_on: vec![],
                dry_run_first: false,
            }],
        };
        let json = serde_json::to_string(&plan).unwrap();
        let parsed: CandidatePlan = serde_json::from_str(&json).unwrap();
        assert_eq!(parsed.id, "test-1");
        assert_eq!(parsed.steps.len(), 1);
    }

    #[test]
    fn test_resolve_path() {
        let root = Path::new("/workspace");
        assert_eq!(resolve_path(root, "src/main.rs"), PathBuf::from("/workspace/src/main.rs"));
        assert_eq!(resolve_path(root, "/tmp/absolute.rs"), PathBuf::from("/tmp/absolute.rs"));
    }
}
