async fn copy_workspace_lightweight(from: &Path, to: &Path) -> Result<()> {
    let skip_dirs = ["target", ".git", ".pharmakon", "node_modules", ".fastembed_cache"];
    let mut entries = tokio::fs::read_dir(from).await?;
    while let Some(entry) = entries.next_entry().await? {
        let path = entry.path();
        let dest = to.join(entry.file_name());
        let name = entry.file_name();
        let name_str = name.to_string_lossy();
        if path.is_dir() {
            if skip_dirs.contains(&name_str.as_ref()) { continue; }
            if name_str.starts_with('.') && name_str != ".cargo" { continue; }
            tokio::fs::create_dir_all(&dest).await?;
            Box::pin(copy_workspace_lightweight(&path, &dest)).await?;
        } else if path.is_file() {
            tokio::fs::copy(&path, &dest).await?;
        }
    }
    Ok(())
}

async fn execute_codeact_in_dir(dir: &Path, script: &str) -> Result<String> {
    let engine = crate::orchestration::codeact::CodeActEngine::new(dir.to_path_buf());
    let result = engine.execute(script);
    if result.success { Ok(result.output) }
    else { Err(anyhow!(result.error.unwrap_or_default())) }
}

async fn execute_shell_in_dir(dir: &Path, cmd: &str) -> Result<String> {
    let output = tokio::process::Command::new("sh")
        .arg("-c").arg(cmd)
        .current_dir(dir)
        .output().await
        .map_err(|e| anyhow!("shell: {}", e))?;
    if output.status.success() {
        Ok(String::from_utf8_lossy(&output.stdout).to_string())
    } else {
        Err(anyhow!("{}", String::from_utf8_lossy(&output.stderr)))
    }
}

async fn apply_patch_in_dir(dir: &Path, file_path: &str, patch_text: &str) -> bool {
    let resolved = resolve_path(dir, file_path);
    let Ok(original) = tokio::fs::read_to_string(&resolved).await else { return false; };
    let Ok(patch) = diffy::Patch::from_str(patch_text) else { return false; };
    let Ok(patched) = diffy::apply(&original, &patch) else { return false; };
    tokio::fs::write(&resolved, patched).await.is_ok()
}

async fn run_cargo_check(dir: &Path) -> bool {
    tokio::process::Command::new("cargo")
        .arg("check")
        .current_dir(dir)
        .output()
        .await
        .map(|o| o.status.success())
        .unwrap_or(false)
}

async fn run_rlfc_validation(dir: &Path) -> Result<()> {
    let output = tokio::process::Command::new("cargo")
        .arg("check")
        .current_dir(dir)
        .output()
        .await
        .map_err(|e| anyhow!("cargo check: {}", e))?;

    if output.status.success() {
        Ok(())
    } else {
        let stderr = String::from_utf8_lossy(&output.stderr);
        Err(anyhow!("validation failed: {}", &stderr[..stderr.len().min(500)]))
    }
}

fn resolve_path(root: &Path, path: &str) -> PathBuf {
    let p = Path::new(path);
    if p.is_absolute() { p.to_path_buf() } else { root.join(p) }
}

