/// Generate 3-5 candidate plans from an LLM.
pub async fn generate_candidate_plans(
    agent: &Agent,
    task: &str,
    context: &str,
    max_plans: usize,
) -> Result<Vec<CandidatePlan>> {
    let tool_list = {
        let reg = agent.registry.lock().await;
        let metadata = reg.all_metadata();
        metadata.iter()
            .filter(|m| m.category == pharmakon_common::ToolCategory::Core)
            .map(|m| format!("- {}: {}", m.name, m.description))
            .collect::<Vec<_>>()
            .join("\n")
    };

    let prompt = format!(
        r#"You are a strategic planner for an autonomous coding agent. Given the task below, generate {max_plans} candidate action plans.

Each plan should have concrete steps using the available tools. Output valid JSON only.

Available tools:
{tool_list}

Task: {task}

Context: {context}

Output format:
```json
[
  {{
    "id": "plan-1",
    "description": "Brief approach description",
    "estimated_tokens": 500,
    "steps": [
      {{
        "tool": "codeact",
        "args": {{"script": "..."}},
        "depends_on": [],
        "dry_run_first": false
      }}
    ]
  }}
]
```

Rules:
- Steps execute in order unless depends_on specifies otherwise
- Mark destructive steps (rm, git push) with dry_run_first: true
- Use direct tools (shell, write_file, read_file, grep_files) for single operations. DO NOT wrap single commands in codeact. Only use codeact for genuinely compound file/code work (3+ sequential tool calls on the same file set, e.g. grep→filter→write). If a task can be done with one shell command, use shell.
- Each plan should be a distinct strategy, not variations of the same idea
- estimated_tokens: your rough guess of API token cost for this plan

Reply with ONLY the JSON array, no explanation."#,
        max_plans = max_plans.max(3).min(5),
        tool_list = tool_list,
        task = task,
        context = context,
    );

    let model = {
        let m = agent.model.lock().await;
        (*m).clone()
    };

    let request = CompletionRequest {
        messages: vec![Message {
            role: "user".to_string(),
            content: Some(MessageContent::Text(prompt)),
            ..Default::default()
        }],
        temperature: Some(0.3),
        max_tokens: Some(2048),
        tools: None,
    };

    let response = model.complete(request).await.map_err(|e| anyhow!("Plan generation failed: {}", e))?;
    let text = response.content.as_ref()
        .and_then(|c| c.as_text())
        .ok_or_else(|| anyhow!("Empty response from planner"))?;

    // Extract JSON from code block if present
    let json_text = if let Some(start) = text.find("```json") {
        let inner = &text[start + 7..];
        if let Some(end) = inner.find("```") {
            &inner[..end]
        } else { inner }
    } else if let Some(start) = text.find('[') {
        &text[start..]
    } else {
        text
    };

    let plans: Vec<CandidatePlan> = serde_json::from_str(json_text.trim())
        .map_err(|e| anyhow!("Failed to parse plans: {}. Raw: {}", e, &json_text[..json_text.len().min(200)]))?;

    if plans.is_empty() {
        return Err(anyhow!("Zero plans generated"));
    }

    log::info!(
        "WorldModel: generated {} plans for task '{}'",
        plans.len(),
        &task[..task.len().min(60)]
    );

    Ok(plans)
}

