/// Simulate a single plan in an isolated temp workspace.
/// Returns PlanValidation with scores.
pub async fn simulate_plan(
    _agent: &Agent,
    plan: &CandidatePlan,
    workspace_root: &Path,
) -> Result<PlanValidation> {
    let start = std::time::Instant::now();
    let temp_dir = tempfile::tempdir()?;
    let sim_root = temp_dir.path();

    log::info!("WorldModel: simulating plan '{}'", plan.id);

    // 1. Copy workspace to temp dir (skip heavy dirs)
    copy_workspace_lightweight(workspace_root, sim_root).await?;

    // 2. Execute steps sequentially (respecting depends_on)
    let mut step_results: Vec<bool> = vec![false; plan.steps.len()];
    let mut issues = Vec::new();

    for (i, step) in plan.steps.iter().enumerate() {
        // Check dependencies
        let deps_ok = step.depends_on.iter().all(|&dep_idx| {
            dep_idx < i && step_results.get(dep_idx).copied().unwrap_or(false)
        });
        if !deps_ok {
            issues.push(format!("Step {} has unmet dependencies", i));
            continue;
        }

        let success = match step.tool.as_str() {
            "codeact" => {
                execute_codeact_in_dir(sim_root, step.args.get("script")
                    .and_then(|s| s.as_str())
                    .unwrap_or(""))
                    .await
                    .is_ok()
            }
            "shell" => {
                execute_shell_in_dir(sim_root, step.args.get("command")
                    .and_then(|s| s.as_str())
                    .unwrap_or(""))
                    .await
                    .is_ok()
            }
            "write_file" => {
                let path = step.args.get("path").and_then(|s| s.as_str()).unwrap_or("");
                let content = step.args.get("content").and_then(|s| s.as_str()).unwrap_or("");
                let resolved = resolve_path(sim_root, path);
                tokio::fs::create_dir_all(resolved.parent().unwrap_or(Path::new("."))).await.ok();
                tokio::fs::write(&resolved, content).await.is_ok()
            }
            "apply_patch" => {
                let path = step.args.get("path").and_then(|s| s.as_str()).unwrap_or("");
                let patch = step.args.get("patch").and_then(|s| s.as_str()).unwrap_or("");
                apply_patch_in_dir(sim_root, path, patch).await
            }
            _ => {
                // Unknown tool in simulation — skip
                log::debug!("WorldModel: skipping unknown tool '{}' in simulation", step.tool);
                true
            }
        };

        step_results[i] = success;
        if !success {
            issues.push(format!("Step {} ({}) failed", i, step.tool));
        }
    }

    // 3. Run cargo check
    let cargo_ok = run_cargo_check(sim_root).await;
    if !cargo_ok {
        issues.push("cargo check failed in simulation".to_string());
    }

    // 4. Score
    let all_steps_ok = step_results.iter().all(|&r| r);
    let mcts_score = score_plan(all_steps_ok, cargo_ok, plan.estimated_tokens);

    let evpi_estimator = EvpiEstimator::new(
        0.5, // moderate genome similarity (new plan)
        0.7, // deep task complexity
        0.8, // cached success rate
    );

    let elapsed = start.elapsed().as_millis();
    log::info!(
        "WorldModel: plan '{}' scored {:.3} (steps_ok={}, cargo_ok={}, {}ms)",
        plan.id, mcts_score, all_steps_ok, cargo_ok, elapsed
    );

    Ok(PlanValidation {
        plan_id: plan.id.clone(),
        valid: all_steps_ok && cargo_ok,
        issues,
        mcts_score,
        token_cost: plan.estimated_tokens,
        evpi: evpi_estimator.evpi(),
    })
}

fn score_plan(steps_ok: bool, cargo_ok: bool, estimated_tokens: u64) -> f64 {
    let step_score = if steps_ok { 0.4 } else { 0.0 };
    let cargo_score = if cargo_ok { 0.4 } else { 0.0 };
    // Token efficiency: cheaper plans score higher
    let token_score = if estimated_tokens > 0 {
        (0.2 * 2000.0 / estimated_tokens as f64).min(0.2)
    } else { 0.1 };
    step_score + cargo_score + token_score
}

// ═══════════════════════════════════════════════════════
// Commit & Rollback Loop
// ═══════════════════════════════════════════════════════

/// Main World Model execution: generate → simulate → commit → verify → rollback on failure.
pub async fn execute_world_model(
    agent: &Agent,
    _session_id: &str,
    task: &str,
) -> Result<String> {
    let workspace_root = std::env::current_dir().unwrap_or_default();

    // Phase 1: Generate candidate plans
    let plans = generate_candidate_plans(agent, task, "", 4).await?;

    // Phase 2: Simulate all plans in parallel
    let sim_futures: Vec<_> = plans.iter().map(|plan| {
        simulate_plan(agent, plan, &workspace_root)
    }).collect();

    let sim_results: Vec<Result<PlanValidation>> = futures::future::join_all(sim_futures).await;

    // Collect validations, sort by score
    let mut validations: Vec<(usize, PlanValidation)> = sim_results.into_iter()
        .enumerate()
        .filter_map(|(i, r)| r.ok().map(|v| (i, v)))
        .collect();

    validations.sort_by(|a, b| b.1.mcts_score.partial_cmp(&a.1.mcts_score).unwrap_or(std::cmp::Ordering::Equal));

    if validations.is_empty() {
        return Err(anyhow!("All plan simulations failed"));
    }

    log::info!(
        "WorldModel: best plan '{}' with score {:.3}. {} candidates simulated.",
        validations[0].1.plan_id,
        validations[0].1.mcts_score,
        validations.len()
    );

    // Phase 3: Commit best plan, fall through on failure
    for (idx, _validation) in &validations {
        let plan = &plans[*idx];

        // Record event_id for rollback checkpoint
        let _checkpoint_id = format!("world_model_{}_{}", plan.id, uuid::Uuid::new_v4().to_string().chars().take(8).collect::<String>());

        // Snapshot files the plan touches
        let mut snapshotted_files: Vec<(PathBuf, String)> = Vec::new();
        for step in &plan.steps {
            if step.tool == "write_file" || step.tool == "apply_patch" {
                if let Some(path_str) = step.args.get("path").and_then(|s| s.as_str()) {
                    let resolved = resolve_path(&workspace_root, path_str);
                    if resolved.exists() {
                        if let Ok(snap_id) = agent.snapshot_store.snapshot_file(&resolved).await {
                            snapshotted_files.push((resolved, snap_id));
                        }
                    }
                }
            }
        }

        // Execute plan steps
        let mut all_ok = true;
        for step in &plan.steps {
            let result = match step.tool.as_str() {
                "codeact" => {
                    let engine = crate::orchestration::codeact::CodeActEngine::new(workspace_root.clone());
                    let script = step.args.get("script").and_then(|s| s.as_str()).unwrap_or("");
                    let r = engine.execute(script);
                    if r.success { Ok(r.output) } else { Err(anyhow!(r.error.unwrap_or_default())) }
                }
                "shell" => {
                    let cmd = step.args.get("command").and_then(|s| s.as_str()).unwrap_or("");
                    let output = tokio::process::Command::new("sh").arg("-c").arg(cmd)
                        .output().await
                        .map_err(|e| anyhow!("shell failed: {}", e))?;
                    if output.status.success() {
                        Ok(String::from_utf8_lossy(&output.stdout).to_string())
                    } else {
                        Err(anyhow!("shell failed: {}", String::from_utf8_lossy(&output.stderr)))
                    }
                }
                _ => {
                    // Delegate to agent's tool registry
                    let mut reg = agent.registry.lock().await;
                    match reg.hydrate(&step.tool) {
                        Some(tool) => {
                            tool.call(step.args.clone()).await
                                .map_err(|e| anyhow!("{}", e.0))
                        }
                        None => Err(anyhow!("Tool not found: {}", step.tool)),
                    }
                }
            };

            if let Err(e) = result {
                log::warn!("WorldModel: plan '{}' step '{}' failed: {}", plan.id, step.tool, e);
                all_ok = false;
                break;
            }
        }

        if all_ok {
            // Run RLFC validation
            if run_cargo_check(&workspace_root).await {
                log::info!("WorldModel: plan '{}' committed and validated successfully", plan.id);
                return Ok(format!(
                    "✅ Plan '{}' executed successfully ({})",
                    plan.id, plan.description
                ));
            }
        }

        // Rollback on failure
        log::warn!("WorldModel: rolling back plan '{}'", plan.id);
        for (path, snap_id) in &snapshotted_files {
            if let Err(e) = agent.snapshot_store.restore(snap_id, path).await {
                log::error!("WorldModel: rollback failed for {}: {}", path.display(), e);
            }
        }
    }

    Err(anyhow!("All {} candidate plans failed. Last plan: {:?}",
        validations.len(),
        validations.last().map(|v| &v.1.plan_id)
    ))
}

