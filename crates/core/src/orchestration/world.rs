//! World Model Agent — Simulate-before-acting execution loop.
//!
//! Replaces reactive CodeAct retry loops with:
//!   1. Generate 3-5 candidate plans (LLM)
//!   2. Simulate each in isolated temp workspace (MCTS + cargo check)
//!   3. Score plans by success probability, token cost, EVPI
//!   4. Commit best plan atomically (SnapshotStore checkpoint)
//!   5. On failure: rollback_to_event() → try next plan
//!
//! Activated for Deep tasks; Simple/Standard tasks skip to standard CodeAct.

use crate::agent::Agent;
use crate::model::{CompletionRequest, Message, MessageContent};
use crate::orchestration::cognitive_economics::EvpiEstimator;
use anyhow::{Result, anyhow};
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

// ═══════════════════════════════════════════════════════
// Plan Types
// ═══════════════════════════════════════════════════════

/// A candidate action plan generated by the LLM.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CandidatePlan {
    pub id: String,
    /// Human-readable description of the approach.
    pub description: String,
    /// Estimated token cost for this plan.
    #[serde(default)]
    pub estimated_tokens: u64,
    /// Steps to execute (CodeAct scripts or tool calls).
    pub steps: Vec<PlanStep>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlanStep {
    /// Tool name to invoke (e.g., "codeact", "write_file", "shell").
    pub tool: String,
    /// Arguments for the tool.
    pub args: serde_json::Value,
    /// Dependencies on previous step indices (for ParallelExecutor).
    #[serde(default)]
    pub depends_on: Vec<usize>,
    /// Dry-run first for destructive operations.
    #[serde(default)]
    pub dry_run_first: bool,
}

/// Validation and scoring result for a plan after simulation.
#[derive(Debug, Clone)]
pub struct PlanValidation {
    pub plan_id: String,
    pub valid: bool,
    pub issues: Vec<String>,
    /// Score 0.0–1.0: estimated success probability.
    pub mcts_score: f64,
    /// Estimated token cost from simulation.
    pub token_cost: u64,
    /// EVPI: expected value of new information from executing this plan.
    pub evpi: f64,
}

